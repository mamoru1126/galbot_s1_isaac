#!/usr/bin/env python3
"""Generate the URDF files used by the Isaac Sim app (committed to urdf/).

    python3 galbot_s1_isaac/tools/generate_urdf.py            # needs xacro (ROS 2 sourced)
    python3 galbot_s1_isaac/tools/generate_urdf.py --check    # exit 1 if the files are outdated

Outputs
  urdf/galbot_s1.urdf        expanded galbot_s1_description xacro (no mimic joints,
                             package:// mesh URIs). Used by the kinematic test backend.
  urdf/galbot_s1_isaac.urdf  the same robot prepared for the Isaac Sim URDF importer:
      * planar base: isaac_world -(base_x_joint, prismatic x)- base_x_link
                     -(base_y_joint, prismatic y)- base_y_link
                     -(base_yaw_joint, continuous z)- base_footprint
        The importer anchors isaac_world to the world (fix_base=True), so the base is
        moved through three driven joints instead of wheel friction (same idea as the
        planar base of the Gazebo version / the official MuJoCo model).
      * wheels without collision shapes (they are only animated)
      * explicit small inertials for frame-only links (PhysX needs a mass on every link)
      * no <mimic> (the gripper joints are commanded explicitly, like in Gazebo)

The Isaac importer does not read xacro, which is why the expanded files are committed;
CI runs this script with --check.
"""
import argparse
import copy
import os
import subprocess
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
REPO = os.path.dirname(PKG)
XACRO = os.path.join(REPO, 'galbot_s1_description', 'urdf', 'galbot_s1.urdf.xacro')
MESH_URI = 'package://galbot_s1_description/meshes'

PLANAR_JOINTS = ('base_x_joint', 'base_y_joint', 'base_yaw_joint')
WHEEL_LINK_PREFIXES = ('wheel_steering_link', 'wheel_driving_link')

HEADER = ('\n  GENERATED by galbot_s1_isaac/tools/generate_urdf.py from\n'
          '  galbot_s1_description/urdf/galbot_s1.urdf.xacro - do not edit by hand.\n  %s\n')


def run_xacro(xacro_cmd):
    """xacro with $(find galbot_s1_description) resolving to this checkout (no colcon build
    needed): a temporary ament prefix whose share/galbot_s1_description links to the source."""
    import tempfile
    prefix = tempfile.mkdtemp(prefix='galbot_ament_')
    index = os.path.join(prefix, 'share', 'ament_index', 'resource_index', 'packages')
    os.makedirs(index)
    open(os.path.join(index, 'galbot_s1_description'), 'w').close()
    os.symlink(os.path.join(REPO, 'galbot_s1_description'), os.path.join(prefix, 'share', 'galbot_s1_description'))
    env = dict(os.environ)
    env['AMENT_PREFIX_PATH'] = prefix + os.pathsep + env.get('AMENT_PREFIX_PATH', '')
    args = [XACRO, 'use_mimic:=false', 'mesh_uri:=' + MESH_URI]
    return subprocess.check_output([xacro_cmd] + args, env=env).decode()


def _inertial(mass, inertia):
    el = ET.Element('inertial')
    ET.SubElement(el, 'origin', xyz='0 0 0', rpy='0 0 0')
    ET.SubElement(el, 'mass', value=repr(mass))
    ET.SubElement(el, 'inertia', ixx=repr(inertia), ixy='0', ixz='0', iyy=repr(inertia), iyz='0',
                  izz=repr(inertia))
    return el


def _link(name, mass=1.0, inertia=0.01):
    el = ET.Element('link', name=name)
    el.append(_inertial(mass, inertia))
    return el


def _joint(name, jtype, parent, child, axis, lower=None, upper=None):
    el = ET.Element('joint', name=name, type=jtype)
    ET.SubElement(el, 'origin', xyz='0 0 0', rpy='0 0 0')
    ET.SubElement(el, 'parent', link=parent)
    ET.SubElement(el, 'child', link=child)
    ET.SubElement(el, 'axis', xyz=axis)
    lim = {'effort': '1000000', 'velocity': '5'}
    if lower is not None:
        lim.update(lower=repr(lower), upper=repr(upper))
    ET.SubElement(el, 'limit', **lim)
    return el


def strip(root):
    """Remove everything that is not robot structure (and the mimic tags)."""
    for tag in ('gazebo', 'transmission', 'ros2_control'):
        for el in root.findall(tag):
            root.remove(el)
    for j in root.findall('joint'):
        for m in j.findall('mimic'):
            j.remove(m)
    return root


def to_isaac(desc_root):
    root = copy.deepcopy(desc_root)
    links = {l.get('name'): l for l in root.findall('link')}
    children = {j.find('child').get('link') for j in root.findall('joint')}
    roots = [n for n in links if n not in children]
    if roots != ['base_footprint']:
        raise SystemExit('unexpected URDF root(s): %s' % roots)

    for name, link in links.items():
        if name.startswith(WHEEL_LINK_PREFIXES):
            for c in link.findall('collision'):
                link.remove(c)
        if link.find('inertial') is None:
            has_geometry = link.find('visual') is not None or link.find('collision') is not None
            link.insert(0, _inertial(1.0, 0.01) if has_geometry else _inertial(0.01, 1e-5))

    first = list(root).index(next(iter(root.findall('link'))))
    extra = [
        _link('isaac_world'), _link('base_x_link'), _link('base_y_link'),
        _joint('base_x_joint', 'prismatic', 'isaac_world', 'base_x_link', '1 0 0', -50.0, 50.0),
        _joint('base_y_joint', 'prismatic', 'base_x_link', 'base_y_link', '0 1 0', -50.0, 50.0),
        _joint('base_yaw_joint', 'continuous', 'base_y_link', 'base_footprint', '0 0 1'),
    ]
    for i, el in enumerate(extra):
        root.insert(first + i, el)
    return root


def serialize(root, note):
    ET.indent(root, space='  ')
    body = ET.tostring(root, encoding='unicode')
    return '<?xml version="1.0"?>\n<!--%s-->\n%s\n' % (HEADER % note, body)


def build(xacro_cmd, expanded=None):
    text = open(expanded).read() if expanded else run_xacro(xacro_cmd)
    desc = strip(ET.fromstring(text))
    desc_out = serialize(desc, 'Expanded robot description (use_mimic:=false).')
    isaac_out = serialize(to_isaac(desc), 'Prepared for the Isaac Sim URDF importer (planar base joints).')
    return {'galbot_s1.urdf': desc_out, 'galbot_s1_isaac.urdf': isaac_out}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='only compare with the committed files')
    ap.add_argument('--xacro', default='xacro', help='xacro executable (default: python module / xacro)')
    ap.add_argument('--expanded', help='use an already expanded URDF instead of running xacro')
    ap.add_argument('--out', default=os.path.join(PKG, 'urdf'))
    args = ap.parse_args()

    files = build(args.xacro, args.expanded)
    stale = []
    for name, content in files.items():
        path = os.path.join(args.out, name)
        old = open(path).read() if os.path.isfile(path) else None
        if old == content:
            print('up to date: %s' % path)
            continue
        if args.check:
            stale.append(path)
            continue
        with open(path, 'w') as f:
            f.write(content)
        print('wrote %s' % path)
    if stale:
        print('outdated (run galbot_s1_isaac/tools/generate_urdf.py): %s' % ', '.join(stale))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
